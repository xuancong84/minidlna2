#!/usr/bin/env python3
# Generate unidecode_table.c from Python's Unidecode, so that minidlna's
# transliteration (used for sorting live folders) matches
# unidecode.unidecode() exactly, without needing Python at build or run time.
#
# Usage: tools/gen-unidecode-table.py > unidecode_table.c
# Needs: python3-unidecode (pip: Unidecode)
#
# Unidecode is GPL-2.0-or-later, (c) Tomaz Solc, based on Sean M. Burke's
# Text::Unidecode; the generated tables are derived from its data.

import sys
from importlib.metadata import version
from unidecode import unidecode

MAX_CP = 0x110000
SECTIONS = MAX_CP >> 8

pool = ['']		# offset 0 is the empty string
offsets = {'': 0}
size = 1		# bytes used by pool, NULs included
sections = []		# (section number, [256 offsets])

for sec in range(SECTIONS):
    row = []
    used = False
    for lo in range(256):
        cp = (sec << 8) | lo
        s = '' if 0xD800 <= cp <= 0xDFFF else unidecode(chr(cp))
        if cp < 0x80:
            s = chr(cp)		# ASCII maps to itself, NUL included
        if s and cp >= 0x80:
            used = True
        if s not in offsets:
            offsets[s] = size
            pool.append(s)
            size += len(s.encode('ascii')) + 1
        row.append(offsets[s])
    if used or sec == 0:
        sections.append((sec, row))

off_type = 'uint16_t' if size < 0x10000 else 'uint32_t'

def c_str(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch in '"\\':
            out.append('\\' + ch)
        elif 0x20 <= o < 0x7f and ch != '?':	# avoid trigraphs
            out.append(ch)
        else:
            out.append('\\%03o' % o)
    return '"' + ''.join(out) + '\\0"'

w = sys.stdout.write
w('/* Generated by tools/gen-unidecode-table.py from Unidecode %s; do not edit.\n'
  ' *\n'
  ' * Transliteration of Unicode code points to ASCII, identical to Python\'s\n'
  ' * unidecode.unidecode(). Unidecode is GPL-2.0-or-later, (c) Tomaz Solc,\n'
  ' * based on Text::Unidecode by Sean M. Burke.\n'
  ' */\n' % version('Unidecode'))
w('#include <stdint.h>\n#include <stddef.h>\n#include "natsort.h"\n\n')
w('static const char pool[] =\n')
line = ''
for s in pool:
    piece = c_str(s)
    if len(line) + len(piece) > 76:
        w('\t%s\n' % line)
        line = ''
    line += piece
w('\t%s;\n\n' % line)
w('static const %s rows[%d][256] = {\n' % (off_type, len(sections)))
for sec, row in sections:
    w('\t{ /* U+%04X */\n' % (sec << 8))
    for i in range(0, 256, 16):
        w('\t\t' + ', '.join(str(x) for x in row[i:i+16]) + ',\n')
    w('\t},\n')
w('};\n\n')
w('/* Row of each 256-code-point section, -1 when nothing in it transliterates */\n')
w('static const int16_t section_row[%d] = {\n' % SECTIONS)
index = {sec: i for i, (sec, _) in enumerate(sections)}
vals = [str(index.get(sec, -1)) for sec in range(SECTIONS)]
for i in range(0, SECTIONS, 24):
    w('\t' + ', '.join(vals[i:i+24]) + ',\n')
w('};\n\n')
w('const char *\nunidecode_char(uint32_t cp)\n{\n'
  '\tint row;\n\n'
  '\tif (cp >= %d)\n\t\treturn "";\n'
  '\trow = section_row[cp >> 8];\n'
  '\treturn row < 0 ? "" : pool + rows[row][cp & 0xFF];\n}\n' % MAX_CP)
sys.stderr.write('%d sections, %d distinct strings, pool %d bytes, %s offsets\n'
                 % (len(sections), len(pool), size, off_type))
