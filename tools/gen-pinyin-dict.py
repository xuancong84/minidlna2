#!/usr/bin/env python3
# Generate pinyin-dict.txt, the dictionary of sort_transliteration=pinyin,
# from mozillazg's pinyin-data and phrase-pinyin-data (both MIT):
#
#   curl -LO https://raw.githubusercontent.com/mozillazg/pinyin-data/master/pinyin.txt
#   mv pinyin.txt chars.txt
#   curl -LO https://raw.githubusercontent.com/mozillazg/phrase-pinyin-data/master/pinyin.txt
#   tools/gen-pinyin-dict.py chars.txt pinyin.txt > pinyin-dict.txt
#
# Each output line is "<text> <syllable>...": a single character with its
# most common reading, or a phrase. Only phrases that read some character
# differently from that default are kept; the others sort the same either
# way. Syllables are lowercase ASCII without tones (u-umlaut becomes u),
# as ICU's and Unidecode's transliterations write them.

import re
import sys
import unicodedata


def toneless(s):
    s = unicodedata.normalize('NFD', s.strip().lower())
    return ''.join(c for c in s if not unicodedata.combining(c))


def version(path):
    for line in open(path, encoding='utf-8'):
        if line.startswith('# version:'):
            return line.split(':', 1)[1].strip()
    return 'unknown'


chars_path, phrases_path = sys.argv[1], sys.argv[2]

default = {}
for line in open(chars_path, encoding='utf-8'):
    m = re.match(r'U\+([0-9A-F]+):\s*([^#]+)', line)
    if m:
        reading = toneless(m.group(2).split(',')[0])
        if reading.isascii() and reading.isalpha():
            default[chr(int(m.group(1), 16))] = reading

phrases = {}
for line in open(phrases_path, encoding='utf-8'):
    if line.startswith('#') or ':' not in line:
        continue
    word, reading = line.split(':', 1)
    word = word.strip()
    syllables = [toneless(s) for s in reading.split()]
    if (len(syllables) != len(word) or any(c not in default for c in word)
            or not all(s.isascii() and s.isalpha() for s in syllables)):
        continue
    if any(default[c] != s for c, s in zip(word, syllables)):
        phrases[word] = syllables

w = sys.stdout.write
w('# minidlna pinyin dictionary, generated by tools/gen-pinyin-dict.py\n')
w('# from pinyin-data %s and phrase-pinyin-data %s (MIT, mozillazg)\n'
  % (version(chars_path), version(phrases_path)))
w('# %d characters with their most common reading, %d phrases that read\n'
  '# a character differently\n' % (len(default), len(phrases)))
for c in sorted(default):
    w('%s %s\n' % (c, default[c]))
for p in sorted(phrases):
    w('%s %s\n' % (p, ' '.join(phrases[p])))
sys.stderr.write('%d characters, %d phrases\n' % (len(default), len(phrases)))
